"""Generate the static footer's true 16px OFL Noto raster and text tokens.

Uses the existing 24px generator's character order without modifying its ROM
or header. New footer-only characters are appended to the shared glyph IDs.
"""
from pathlib import Path
import argparse,hashlib,json
from PIL import Image,ImageDraw,ImageFont
from generate_lcd_cjk24 import TEXTS,font_names

ROOT=Path(__file__).resolve().parents[1]
FOOTERS={
    'LIVE_0':'键1切实时/录放 长按2秒复位',
    'LIVE_1':'键2切原声/变调/和声/双变调',
    'LIVE_2':'旋1转调增益 按下切麦克风/静音',
    'LIVE_3':'旋2转调半音 短按归零/选声部 长按2秒归零',
    'CLIP_0':'键1切实时/录放 长按2秒复位 键2切音效',
    'CLIP_1':'键3录音/结束 键4播放/暂停/继续',
    'CLIP_2':'旋1转调增益 旋2转调半音',
    'CLIP_3':'旋2短按归零/选声部 长按2秒归零 键4长按重播',
}
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--font',default='C:/Windows/Fonts/NotoSansSC-VF.ttf');ap.add_argument('--check',action='store_true');a=ap.parse_args()
    source=Path(a.font).read_bytes();names=font_names(source)
    assert 'Open Font License' in names.get('13','')
    original=list(dict.fromkeys(' 0123456789+-.?/:ABCDEF'+''.join(TEXTS.values())))
    chars=list(dict.fromkeys(''.join(original)+''.join(FOOTERS.values())))
    assert len(chars)<=128
    ids={char:i for i,char in enumerate(chars)}
    font=ImageFont.truetype(a.font,16);font.set_variation_by_axes([650])
    rows=[0]*2048;glyphs=[]
    atlas=Image.new('RGB',(16*32,((len(chars)+15)//16)*48),'#101820');pen=ImageDraw.Draw(atlas)
    for i,char in enumerate(chars):
        box=font.getbbox(char);width,height=box[2]-box[0],box[3]-box[1]
        cell_width=8 if ord(char)<128 else 16
        canvas=Image.new('L',(max(width,1),max(height,1)),0)
        ImageDraw.Draw(canvas).text((-box[0],-box[1]),char,font=font,fill=255)
        # Some hinted 16px CJK glyphs have a 17px overshoot. Fit that single
        # pixel rather than clipping a stroke; no 24px raster is reused.
        if width>cell_width or height>16:
            canvas=canvas.resize((min(cell_width,canvas.width),min(16,canvas.height)),Image.Resampling.LANCZOS)
        glyph=Image.new('1',(16,16),0)
        mask=canvas.point(lambda v:255 if v>=112 else 0).convert('1')
        glyph.paste(mask,((cell_width-mask.width)//2,(16-mask.height)//2))
        for y in range(16):
            bits=0
            for x in range(16):bits=(bits<<1)|bool(glyph.getpixel((x,y)))
            rows[i*16+y]=bits
        assert char==' ' or glyph.getbbox(),char
        glyphs.append(dict(id=i,character=char,cell_width=cell_width,ink_bounds=glyph.getbbox()))
        tile=Image.new('RGB',(16,16),'#101820');tile.paste('white',(0,0),glyph)
        left,top=(i%16)*32,(i//16)*48
        atlas.paste(tile.resize((32,32),Image.Resampling.NEAREST),(left,top));pen.text((left+1,top+33),str(i),fill='white')
    header=['// Generated by tools/generate_lcd_cjk16.py. True 16px fixed footer.',
            '// Same glyph IDs as lcd_ui_text.vh; footer-only IDs are appended.',
            'localparam integer LCD_FOOTER_CELLS=56;']
    for name,text in FOOTERS.items():
        tokens=[]
        for char in text:
            tokens.append(ids[char])
            if ord(char)>=128:tokens.append(ids[char]+256)
        assert len(tokens)<=56,(name,text)
        header += [f'// {name}: {text} ({len(tokens)} half-cells)',f'localparam integer NF_{name}={len(tokens)};']
        tokens += [0]*(56-len(tokens))
        header.append(f'localparam [503:0] TF_{name}={{'+','.join(f"9'd{v}" for v in tokens)+'};')
    outputs={ROOT/'src/lcd_cjk16.mem':''.join(f'{v:04x}\n' for v in rows),ROOT/'src/lcd_footer_text.vh':'\n'.join(header)+'\n'}
    for p,data in outputs.items():
        if a.check:assert p.read_text(encoding='utf-8')==data,p
        else:p.write_text(data,encoding='utf-8',newline='\n')
    if not a.check:
        out=ROOT/'docs/fonts';out.mkdir(exist_ok=True)
        metadata=dict(SubsetName='FPGA Audio LCD CJK16 Footer Subset',SourceFamily=names.get('1'),SourceSHA256=hashlib.sha256(source).hexdigest().upper(),FontSize=16,Weight=650,BinaryThreshold=112,GlyphCount=len(chars),OriginalSharedGlyphIDs=len(original),NewFooterOnlyChars=chars[len(original):],Glyphs=glyphs,Rows=2048,RowWidth=16,ROM_SHA256=hashlib.sha256(outputs[ROOT/'src/lcd_cjk16.mem'].encode()).hexdigest().upper(),FixedPages=FOOTERS)
        (out/'GLYPH16_MANIFEST.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        atlas.save(out/'glyph16_atlas.png')
    print(f'PASS CJK16 footer: {len(chars)} glyphs, 2048x16-bit ROM, 2 fixed pages, 4 rows each')
if __name__=='__main__':main()
